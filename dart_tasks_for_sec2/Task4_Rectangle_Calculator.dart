void main() {
  double width = 8;
  double height = 5;
  /// Calculate area and perimeter
  double area = width * height;
  double perimeter = 2 * (width + height);
  print("Width = ${width.toInt()}\nHeight = ${height.toInt()}\nArea = ${area.toInt()}\nPerimeter = ${perimeter.toInt()}");
  // Output:
  // Width = 8
  // Height = 5
  // Area = 40
  // Perimeter = 26
}
