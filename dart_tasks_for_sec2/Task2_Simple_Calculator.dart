void main() {
  int num1 = 15;
  int num2 = 4;
  /// Perform basic arithmetic operations
  int sum = num1 + num2;
  int difference = num1 - num2;
  int product = num1 * num2;
  double Division = num1 / num2;
  print("Sum = ${sum}\nDifference = ${difference}\nProduct = ${product}\nDivision = ${Division.toStringAsFixed(2)}");
  // Output:
  // Sum = 19
  // Difference = 11
  // Product = 60
  // Division = 3.75
}
